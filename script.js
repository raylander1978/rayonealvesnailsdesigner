function readSavedLanguage() {
    try {
        const language = window.localStorage.getItem('rayone-language');
        return Object.hasOwn(translations, language) ? language : 'pt-BR';
    } catch (error) {
        if (error instanceof DOMException && error.name === 'SecurityError') return 'pt-BR';
        throw error;
    }
}

let currentLanguage = readSavedLanguage();

function translatePage(language) {
    const dictionary = translations[language];
    document.documentElement.lang = language;

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const text = dictionary[element.dataset.i18n];
        if (text !== undefined) element.textContent = text;
    });
    document.querySelectorAll('[data-i18n-html]').forEach(element => {
        const html = dictionary[element.dataset.i18nHtml];
        if (html !== undefined) element.innerHTML = html;
    });
    ['alt', 'aria-label', 'placeholder', 'content', 'title'].forEach(attribute => {
        document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
            const text = dictionary[element.dataset[`i18n${attribute[0].toUpperCase()}${attribute.slice(1)}`]];
            if (text !== undefined) element.setAttribute(attribute, text);
        });
    });
    document.querySelectorAll('[data-wa-message]').forEach(link => {
        const message = dictionary[`whatsapp.${link.dataset.waMessage}`];
        if (message !== undefined) {
            link.href = `https://wa.me/5531971643629?text=${encodeURIComponent(message)}`;
        }
    });
    document.querySelectorAll('.language-button').forEach(button => {
        const isActive = button.dataset.language === language;
        button.classList.toggle('active', isActive);
        button.setAttribute('aria-pressed', String(isActive));
    });
}

function initLanguageSwitcher() {
    document.querySelectorAll('.language-button').forEach(button => {
        button.addEventListener('click', () => {
            currentLanguage = button.dataset.language;
            translatePage(currentLanguage);
            try {
                window.localStorage.setItem('rayone-language', currentLanguage);
            } catch (error) {
                if (!(error instanceof DOMException && error.name === 'SecurityError')) throw error;
            }
        });
    });

    translatePage(currentLanguage);
}

